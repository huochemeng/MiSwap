CREATE TABLE `activity_sepolia`
(
    `id`                 BIGINT          NOT NULL AUTO_INCREMENT COMMENT '主键',
    `activity_type`      TINYINT         NOT NULL COMMENT '活动类型(1:Buy 2:Mint 3:List 4:CancelList 5:CancelOffer 6:MakeOffer 7:Sell 8:Transfer)',
    `maker`              VARCHAR(255)    NOT NULL DEFAULT '' COMMENT '发起方地址',
    `taker`              VARCHAR(255)    NOT NULL DEFAULT '' COMMENT '对手方地址',
    `marketplace_id`     TINYINT         NOT NULL DEFAULT 0 COMMENT '市场ID',
    `collection_address` VARCHAR(255)    NOT NULL DEFAULT '' COMMENT '所属Collection合约地址',
    `token_id`           VARCHAR(255)    NOT NULL DEFAULT '' COMMENT 'NFT Token ID',
    `currency_address`   VARCHAR(255)    NOT NULL DEFAULT '' COMMENT '支付代币合约地址',
    `price`              DECIMAL(30, 10) NOT NULL DEFAULT 0.0000000000 COMMENT '成交价格',
    `sell_price`         DECIMAL(30, 10) NOT NULL DEFAULT 0.0000000000 COMMENT '卖方价格',
    `buy_price`          DECIMAL(30, 10) NOT NULL DEFAULT 0.0000000000 COMMENT '买方价格',
    `block_number`       BIGINT(20)      NOT NULL COMMENT '区块高度',
    `tx_hash`            VARCHAR(255)    NOT NULL COMMENT '交易哈希',
    `event_time`         BIGINT(20)      NOT NULL DEFAULT 0 COMMENT '链上事件发生时间(秒级时间戳)',
    `create_time`        BIGINT(20)      NOT NULL COMMENT '创建时间(毫秒级时间戳)',
    `update_time`        BIGINT(20)      NOT NULL COMMENT '更新时间(毫秒级时间戳)',
    PRIMARY KEY (`id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci COMMENT ='Sepolia链NFT活动记录表';

# Activity 表是典型的写多读少 + 多维度查询表，索引设计需兼顾写入性能和查询覆盖
-- 交易哈希唯一约束，防止链上事件重复入库
ALTER TABLE `activity_sepolia` ADD UNIQUE INDEX `uk_tx_hash` (`tx_hash`);

-- Collection详情页的活动流（按时间倒序）
ALTER TABLE `activity_sepolia` ADD INDEX `idx_collection_event_time` (`collection_address`, `event_time` DESC);

-- Item详情页的活动流
ALTER TABLE `activity_sepolia` ADD INDEX `idx_collection_token_event_time` (`collection_address`, `token_id`, `event_time` DESC);

-- 按用户查"我的活动记录"
ALTER TABLE `activity_sepolia` ADD INDEX `idx_maker_event_time` (`maker`, `event_time` DESC);

-- 按活动类型筛选（如只看成交/只看上架）
ALTER TABLE `activity_sepolia` ADD INDEX `idx_activity_type` (`activity_type`);

-- 区块范围查询（同步补漏/重放）
ALTER TABLE `activity_sepolia` ADD INDEX `idx_block_number` (`block_number`);

